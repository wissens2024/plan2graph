#!/usr/bin/env python3
"""role_rules — **역할 쌍이 무엇으로 이어지는가**를 데이터로 적어둔다(눈대중 금지).

사용자가 도면 한 장을 직접 보고 알려준 사실들을 규칙으로 옮긴 것이다
(2026-11-13). 규칙은 코드가 아니라 **표**다 — 틀렸으면 표만 고친다.

왜 필요한가: 문·창 검출은 "여기 개구부가 있다"까지만 말해준다. 그것이 어느 두 방을
잇는지는 기하로 풀리지만, **무엇으로** 이어지는지(문/창/개방)는 기하만으로는 틀린다.
실측: 알파룸↔발코니 경계에 `type=open` 벽 레코드가 있어 개방으로 적혔는데,
사용자 확인은 *"알파룸과 발코니는 창문으로 연결되어 있다. 오픈 공간 아니다"* 였다.

⚠ 과잉 일반화 금지. 사용자는 *"도면이 모두 같은 구조가 아니야"* 라고 했고,
`욕실↔드레스룸`은 이전에 *"파우더룸 없이 붙게 되면 문이 문제더라"* 라고 했으므로
**금지 쌍이 아니다**(그 도면 한정 사실이다). 여기에는 **여러 도면에 걸쳐 성립하는
것만** 적는다. 도면 한 장짜리 사실은 `_edit_log.jsonl` 에만 남긴다.
"""
from __future__ import annotations

# ── 발코니로 통하는 쪽 ────────────────────────────────────────────
# 사용자: "방↔발코니는 창이다" / "발코니와 실외기는 문이 있다. 오픈 공간이 아니다"
#         "드레스룸과 발코니에 문을 만들었다" / "발코니와 현관에 문이 있다"
# 해석: 주거실은 전면 미닫이창(통행형)으로 발코니와 통하고,
#       서비스·수납 공간은 문으로 통한다. 둘 다 '개방'은 아니다.
BALCONY_WINDOW = ("거실", "침실", "안방", "주방", "다목적공간", "가족실", "알파룸", "식당")
BALCONY_DOOR = ("실외기실", "드레스룸", "현관", "펜트리", "팬트리", "창고",
                "세탁실", "다용도실", "보일러실", "대피공간")
BALCONY_ROLES = ("발코니", "테라스")

# ── 문으로 보는 쌍 ────────────────────────────────────────────────
# 사용자: "알파룸은 공사를 해서 문을 달았다. 일반적으로 현관처럼 오픈 공간을 두기도 하고
#          문을 달기도 하는데 많은 사람들이 문을 단다."
# → 문이 검출되면 문, 아니면 개방으로 남긴다(강제하지 않는다). 그래서 표에는 넣지 않고
#   주석으로만 남긴다. 강제하면 '많은 사람들이'를 전수로 단정하는 셈이다.

# ── 문이 있을 수 없는 쌍 ──────────────────────────────────────────
# 침실끼리 문으로 직결되는 한국 아파트는 없다(이 프로그램을 만든 이유).
# 욕실끼리도 없다. 그 외는 도면마다 다르므로 적지 않는다.
FORBID_DOOR = (("침실", "침실"), ("욕실", "욕실"), ("화장실", "화장실"),
               ("침실", "안방"))

# ── 현관 ──────────────────────────────────────────────────────────
# 사용자: "현관복도는 일반적으로 미닫이 또는 인테리어 공사를 안 하면 오픈 공간이다."
# → rebuild_links 의 entrance_rule 로 이미 구현(문이 없을 때만 개방으로 잇는다).
ENTRANCE_OPEN_TO = ("복도", "거실", "주방", "알파룸")


def via_for(role_a, role_b):
    """이 역할 쌍이 무엇으로 이어져야 하는가. 모르면 None(기하 판정을 그대로 둔다)."""
    a, b = role_a or "", role_b or ""
    for x, y in ((a, b), (b, a)):
        if x in BALCONY_ROLES:
            if y in BALCONY_WINDOW:
                return "window"
            if y in BALCONY_DOOR:
                return "door"
            if y in BALCONY_ROLES:
                return None            # 발코니끼리는 이어진 발코니 — 판정 안 함
    return None


def door_forbidden(role_a, role_b):
    a, b = role_a or "", role_b or ""
    return ((a, b) in FORBID_DOOR) or ((b, a) in FORBID_DOOR)
